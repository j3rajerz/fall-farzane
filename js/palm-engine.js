  /**
   * تحلیل بسیار سادهٔ تصویر (فقط برای ساخت بذر و افزودن کمی تنوع بصری به روایت)
   * ورودی: یک 2D context از canvas حاوی عکسِ گرفته‌شده.
   * خروجی: { brightness, contrast, edgeScore } — همگی اعداد نمادین، نه دادهٔ پزشکی یا علمی.
   */
  function analyzeImageData(ctx, width, height) {
    let imgData;
    try {
      imgData = ctx.getImageData(0, 0, width, height).data;
    } catch (e) {
      // در صورت محدودیت مرورگر (مثلاً canvas آلوده)، مقادیر پیش‌فرض بازگردانده می‌شود
      return { brightness: 128, contrast: 20, edgeScore: 10 };
    }

    const sampleStep = 4 * 6; // نمونه‌برداری تُنُک برای کارایی بهتر
    let sum = 0, sumSq = 0, count = 0;
    let edgeSum = 0;
    let prevLum = null;

    for (let i = 0; i < imgData.length; i += sampleStep) {
      const r = imgData[i], g = imgData[i + 1], b = imgData[i + 2];
      const lum = 0.299 * r + 0.587 * g + 0.114 * b;
      sum += lum;
      sumSq += lum * lum;
      count += 1;
      if (prevLum !== null) edgeSum += Math.abs(lum - prevLum);
      prevLum = lum;
    }

    const mean = count ? sum / count : 128;
    const variance = count ? Math.max(0, sumSq / count - mean * mean) : 400;
    const contrast = Math.sqrt(variance);
    const edgeScore = count ? edgeSum / count : 10;

    return { brightness: mean, contrast, edgeScore };
  }

  function uid() {
    return "p_" + Date.now().toString(36) + "_" + Math.random().toString(36).slice(2, 8);
  }

